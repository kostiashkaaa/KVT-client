// Что открыто на странице «Подписки». Одно на все карточки: открыть переименование,
// подтверждение или форму у одной подписки значит закрыть у другой — как было, пока
// всё это жило в одном компоненте.

export class ListUi {
  /** Подписка, у которой правится название. */
  renaming = $state<string | null>(null);
  /** Подписка, удаление которой ждёт подтверждения. */
  confirmRemove = $state<string | null>(null);
  /** Подписка, у которой открыты «Расширенные». */
  advanced = $state<string | null>(null);
  /** Ключ, который сейчас редактируется. */
  editing = $state<string | null>(null);
  /** Ключ, удаление которого ждёт подтверждения. */
  confirmKey = $state<string | null>(null);
}
